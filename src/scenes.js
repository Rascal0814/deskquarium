// plants：图里的水草在哪。气泡只从这些地方冒——水草见了光做光合作用才冒泡（见 ui/render.mjs）。
//   坐标按图片的比例写：x 从左到右 0~1，y 从上到下 0~1；rx / ry 是这丛草左右、上下各占多大。
//   换图的话照着新图重新标：打开图，看每丛草的中心大概在宽、高的百分之几。
const carpet = (from, to, step, y) => {
  const spots = []
  for (let x = from; x <= to + 1e-9; x += step) spots.push({ x: Number(x.toFixed(3)), y, rx: step / 2, ry: 0.012 })
  return spots
}

